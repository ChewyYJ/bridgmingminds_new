import { expect, test } from "@playwright/test";
test.use({ channel: "chrome", permissions: ["microphone"], launchOptions: { args: ["--use-fake-device-for-media-stream", "--use-fake-ui-for-media-stream"] } });
test.setTimeout(90000);
const base = process.env.E2E_WEB_URL || "http://localhost:3002";
for (const size of [{ name: "phone", width: 360, height: 800 }, { name: "desktop", width: 1440, height: 1000 }]) {
  test(`daily hub ${size.name}: both activities, actual rewards and reload`, async ({ page }, info) => {
    await page.setViewportSize(size);
    const errors: string[] = [];
    page.on("pageerror", (e) => errors.push(e.message));
    await page.goto(base);
    await page.getByRole("button", { name: "Try as guest", exact: true }).click();
    await page.getByRole("textbox", { name: "Your name", exact: true }).fill("Alex");
    await page.getByRole("button", { name: "Grow my garden", exact: true }).click();
    const read = page.getByRole("button", { name: "Read aloud", exact: true });
    const spin = page.getByRole("button", { name: "Spin and reflect", exact: true });
    await expect(read).toBeVisible(); await expect(spin).toBeVisible();
    const a = (await read.boundingBox())!, b = (await spin.boundingBox())!;
    expect(size.name === "phone" ? b.y > a.y : Math.abs(b.y - a.y) < 2).toBeTruthy();
    await page.screenshot({ path: info.outputPath("hub.png"), fullPage: true });
    await read.click();
    await expect(page.getByTestId("reading-passage")).toBeVisible();
    await expect(page.getByRole("textbox", { name: "Your reading observation", exact: true })).toHaveCount(0);
    await page.screenshot({ path: info.outputPath("read.png"), fullPage: true });
    await page.getByRole("button", { name: "Done reading", exact: true }).click();
    await page.getByRole("textbox", { name: "Your reading observation", exact: true }).fill("I paused at the commas and practised the final sentence with a slower pace.");
    await page.getByRole("checkbox", { name: "I practised this passage and reviewed my reading", exact: true }).click();
    await page.getByRole("button", { name: "Save reading self-review", exact: true }).click();
    await expect(page.getByTestId("reading-reward")).toHaveText("+10 XP");
    await page.getByRole("button", { name: "Return to daily workout", exact: true }).click();
    await expect(page.getByTestId("daily-progress")).toHaveText("1/2");
    await page.reload(); await expect(page.getByTestId("daily-progress")).toHaveText("1/2");
    await page.getByRole("button", { name: "Spin and reflect", exact: true }).click();
    await page.getByRole("button", { name: "Start brainstorming", exact: true }).waitFor();
    await expect(page.getByRole("button", { name: "Start brainstorming", exact: true })).toBeEnabled();
    await page.screenshot({ path: info.outputPath("spin.png"), fullPage: true });
    await page.getByRole("button", { name: "Start brainstorming", exact: true }).click();
    await page.getByRole("textbox", { name: "My View note", exact: true }).fill("Try a small example first.");
    await page.getByRole("button", { name: "Done brainstorming", exact: true }).click();
    await page.getByRole("button", { name: "Allow Private Recording", exact: true }).click();
    await page.getByRole("button", { name: "Record my response", exact: true }).click();
    await expect(page.getByRole("button", { name: "Finish recording", exact: true })).toBeEnabled();
    await page.getByRole("button", { name: "Finish recording", exact: true }).click();
    await page.getByRole("button", { name: "Use recording", exact: true }).click();
    // Offline test server deliberately has no AI key: use its supported transcript-review path.
    await page.getByRole("textbox", { name: "Transcript", exact: true }).fill("I would start with a small example because it lets us compare the result before making a larger change. Another viewpoint could reveal a problem we have missed, so I would ask someone else to check our reasoning.");
    await page.getByRole("button", { name: "Get Feedback", exact: true }).click();
    await expect(page.getByTestId("daily-screen-feedback")).toBeVisible();
    await page.getByRole("button", { name: "Finish practice", exact: true }).click();
    await expect(page.getByText("+15", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await expect(page.getByTestId("daily-progress")).toHaveText("2/2");
    await page.reload(); await expect(page.getByTestId("daily-progress")).toHaveText("2/2");
    const response = await page.request.get(`${base}/api/state`);
    const state = await response.json();
    expect(state.dailyWorkout.xp).toBe(25);
    expect(state.dailyWorkout.streak.securedToday).toBe(true);
    expect(state.dailyWorkout.activities.every((a: { completed: boolean }) => a.completed)).toBe(true);
    expect(errors).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("completed-hub.png"), fullPage: true });
  });
}
